import {
  Column,
  CreateDateColumn,
  DeleteDateColumn,
  Entity,
  Index,
  JoinColumn,
  ManyToOne,
  PrimaryColumn,
} from 'typeorm';
import { UserKeyStatus } from '../enums';
import { bigintToNumber } from '../transformers';
import { Tariff } from './tariff.entity';
import { User } from './user.entity';

/**
 * A purchased VPN key. Its id is the xray client UUID; the same client is added
 * to every enabled server, so one key gives a link per server.
 */
@Entity({ name: 'user_keys' })
@Index(['userId'])
@Index(['status', 'expiresAt'])
export class UserKey {
  /** Xray client id (UUID v4), generated by the app before the key is created on servers. */
  @PrimaryColumn({ type: 'uuid' })
  id: string;

  @Column({ name: 'user_id', type: 'uuid' })
  userId: string;

  @Column({ name: 'tariff_id', type: 'uuid' })
  tariffId: string;

  @Column({
    type: 'enum',
    enum: UserKeyStatus,
    enumName: 'user_key_status',
    default: UserKeyStatus.Active,
  })
  status: UserKeyStatus;

  @Column({ name: 'expires_at', type: 'timestamptz' })
  expiresAt: Date;

  /** Copied from the tariff at purchase: later tariff edits don't affect sold keys. */
  @Column({ name: 'traffic_limit', type: 'bigint', nullable: true, transformer: bigintToNumber })
  trafficLimit: number | null;

  @Column({ name: 'traffic_used', type: 'bigint', default: 0, transformer: bigintToNumber })
  trafficUsed: number;

  /** Tariff to renew with automatically when the key expires; `null` — no auto-renewal. */
  @Column({ name: 'auto_renew_tariff_id', type: 'uuid', nullable: true })
  autoRenewTariffId: string | null;

  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' })
  createdAt: Date;

  /** Soft delete: the user removed the key from the list. */
  @DeleteDateColumn({ name: 'deleted_at', type: 'timestamptz' })
  deletedAt: Date | null;

  @ManyToOne(() => User, { onDelete: 'CASCADE' })
  @JoinColumn({ name: 'user_id' })
  user?: User;

  @ManyToOne(() => Tariff, { onDelete: 'RESTRICT' })
  @JoinColumn({ name: 'tariff_id' })
  tariff?: Tariff;

  @ManyToOne(() => Tariff, { onDelete: 'SET NULL', nullable: true })
  @JoinColumn({ name: 'auto_renew_tariff_id' })
  autoRenewTariff?: Tariff | null;
}
