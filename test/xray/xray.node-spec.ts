import { randomUUID } from 'node:crypto';
import { GenericContainer, type StartedTestContainer, Wait } from 'testcontainers';
import type { AppConfigService } from '../../src/config/app-config.service';
import { DIRECT_DOMAINS } from '../../src/modules/subscription/domains';
import { buildXrayClientConfig } from '../../src/modules/xray/xray-client-config';
import { type XrayNode, XrayNodeClient } from '../../src/modules/xray/xray-node.client';
import { XrayService } from '../../src/modules/xray/xray.service';

/**
 * Runs against a real xray-server-instance in Docker.
 * Image: XRAY_INSTANCE_IMAGE (default ghcr.io/huayun-vision/xray-instance:latest).
 */
const IMAGE = process.env.XRAY_INSTANCE_IMAGE ?? 'ghcr.io/huayun-vision/xray-instance:latest';
const API_KEY = 'a'.repeat(64);

describe('XrayService against xray-server-instance (node)', () => {
  let container: StartedTestContainer;
  let node: XrayNode;
  let client: XrayNodeClient;
  let xray: XrayService;

  beforeAll(async () => {
    container = await new GenericContainer(IMAGE)
      .withEnvironment({
        API_KEY,
        API_PORT: '440',
        XRAY_PORT: '443',
        GLOBAL_PREFIX: '',
        NODE_ENV: 'production',
        LOG_LEVEL: 'warn',
      })
      .withExposedPorts(440)
      .withWaitStrategy(Wait.forHttp('/health/live', 440).forStatusCode(200))
      .withStartupTimeout(90_000)
      .start();

    node = {
      code: 'test',
      host: container.getHost(),
      apiPort: container.getMappedPort(440),
      apiKey: API_KEY,
    };
    client = new XrayNodeClient({ get: () => 10_000 } as unknown as AppConfigService);
    xray = new XrayService(client);
  });

  afterAll(async () => {
    await container?.stop();
  });

  /** Client ids currently known to the running xray, via its stats-free user listing. */
  async function hasClient(id: string): Promise<boolean> {
    const [out] = await client.run(node, [
      `xray api inbounduser --server=127.0.0.1:10085 --tag=vless-in -email=${id} 2>&1 || true`,
    ]);
    return out.includes(id);
  }

  it('reads reality params generated by the node', async () => {
    const params = await xray.getRealityParams(node);
    expect(params.port).toBe(443);
    expect(params.publicKey).toMatch(/^[\w-]{43}$/);
    expect(params.shortId).toMatch(/^[0-9a-f]{16}$/);
    expect(params.serverName).toBeTruthy();
  });

  it('adds, re-adds and removes a client', async () => {
    const id = randomUUID();

    await xray.addClient(node, id);
    expect(await hasClient(id)).toBe(true);
    const [file] = await client.run(node, [`cat /xray/data/users/${id}.json`]);
    expect(JSON.parse(file)).toMatchObject({ inbounds: [{ tag: 'vless-in' }] });

    // Adding the same client again must not fail.
    await expect(xray.addClient(node, id)).resolves.toBeUndefined();

    await xray.removeClient(node, id);
    expect(await hasClient(id)).toBe(false);
    const [ls] = await client.run(node, ['ls /xray/data/users']);
    expect(ls).not.toContain(id);

    // Removing a missing client is fine too.
    await expect(xray.removeClient(node, id)).resolves.toBeUndefined();
  });

  it('rejects a wrong API key', async () => {
    await expect(client.run({ ...node, apiKey: 'b'.repeat(64) }, ['true'])).rejects.toMatchObject({
      reason: 'unauthorized',
    });
  });

  it('builds a link with the node params', async () => {
    const id = randomUUID();
    const link = await xray.buildVlessLink(node, id, 'Test');
    expect(link).toMatch(new RegExp(`^vless://${id}@${node.host}:443\\?.*security=reality`));
  });

  it('generated client config (with direct domains) is valid for xray', async () => {
    const config = buildXrayClientConfig({
      clientId: randomUUID(),
      host: 'example.com',
      params: await xray.getRealityParams(node),
      label: 'Test',
      directDomains: DIRECT_DOMAINS,
    });
    // The remote shell gets the JSON via base64 to avoid any quoting issues.
    const b64 = Buffer.from(JSON.stringify(config)).toString('base64');
    const [out] = await client.run(node, [
      `echo ${b64} | base64 -d > /tmp/client.json && xray run -test -config /tmp/client.json 2>&1`,
    ]);
    expect(out).toMatch(/Configuration OK/);
  });
});
